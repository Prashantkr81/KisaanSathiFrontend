import { apiRequest } from "./api";

export type CropActivityStatus = "UPCOMING" | "IN_WINDOW" | "PAST_WINDOW";

export type ScheduledActivity = {
  id: string;
  name: string;
  category: string;
  description: string;
  startDayOffset: number;
  endDayOffset: number;
  startDate: string;
  endDate: string;
  status: CropActivityStatus | string;
};

export type CropScheduleResult = {
  farmId: number;
  farmName: string;
  crop: string | null;
  dayCountFrom: string | null;
  referenceDate: string | null;
  message: string;
  activities: ScheduledActivity[];
};

/**
 * Fetches the schedule generated by CropActivitySchedulerService.
 * Expected backend route: GET /api/farms/{farmId}/activities
 * If your controller uses a different @GetMapping, update this URL only.
 */
export function getFarmActivities(farmId: number): Promise<CropScheduleResult> {
  if (!Number.isInteger(farmId) || farmId <= 0) {
    return Promise.reject(new Error("Invalid farm ID."));
  }

  return apiRequest<CropScheduleResult>(`/api/farms/${farmId}/activities`, {
    method: "GET",
  });
}
